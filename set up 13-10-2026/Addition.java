public class Addition {
    public static void main(String[] args) {
        int a = 15;
        int b = 25;
        int sum = a + b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Addition: " + a + " + " + b + " = " + sum);
    }
}
