public class Modulus {
    public static void main(String[] args) {
        int a = 29;
        int b = 4;
        int remainder = a % b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Modulus (Remainder): " + a + " % " + b + " = " + remainder);
    }
}
