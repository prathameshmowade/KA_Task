public class Multiplication {
    public static void main(String[] args) {
        int a = 12;
        int b = 8;
        int product = a * b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Multiplication: " + a + " * " + b + " = " + product);
    }
}
