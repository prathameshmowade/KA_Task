public class Difference {
    public static void main(String[] args) {
        int a = 50;
        int b = 20;
        int diff = a - b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Difference: " + a + " - " + b + " = " + diff);
    }
}
