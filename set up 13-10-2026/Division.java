public class Division {
    public static void main(String[] args) {
        int a = 45;
        int b = 5;
        int quotient = a / b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Division: " + a + " / " + b + " = " + quotient);
    }
}
